"""
Table 2 (v23): adopted C IV measurements.

One row per object with Q = 1, 2 or 3 in Table 1 (the 349 measured objects
plus the 22 IUE objects, which are placeholders until they are measured).
Objects are labelled by the Table 1 index (#, RA order) and common name.

Columns:
  #, Name     -- as in Table 1
  Spectrum    -- the spectrum the measurement was made from (v23 `adopted`:
                 COS, FOS, STIS, or SPLICE = two instruments joined); IUE for
                 the placeholders
  Blueshift   -- C IV blueshift, km/s, positive = blueshifted.  Values are
                 quantised at 69.03 km/s by construction, so printed as integers
  EW          -- C IV equivalent width, Angstrom
  D_CIV       -- C IV distance, computed here from (blueshift, log EW) with
                 Trevor McCaffrey's CIV_distance() and best-fit curve
                 (~/Work/git/CIV_Distance), as in Fig 6a
  Q           -- as in Table 1 (3 measured; 2 measured with a reservation;
                 1 IUE, not yet measured)

Usage:   PYTHONPATH=~/Work/git python make_table2.py
Output:  Tables/table2_civ_v23.tex and Tables/table2_civ_v23.csv
"""

import os
import sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "Data")
OUT_DIR = os.path.join(HERE, "..", "Tables")

CIVDIST_DIR = os.path.expanduser("~/Work/git/CIV_Distance/")
sys.path.insert(0, CIVDIST_DIR)
from CIVfunctions import CIV_distance


def main():
    t = pd.read_csv(os.path.join(DATA, "CIV_measurements_v23.csv"))
    t = t[t["CIVgood_manmask"].isin([1, 2, 3])].sort_values("row_num").reset_index(drop=True)

    # C IV distance for the measured objects (Q = 2 or 3)
    meas = t["CIVgood_manmask"].isin([2, 3]).values
    data = np.array([t.loc[meas, "CIV_blue"].values,
                     np.log10(t.loc[meas, "CIV_EW"].values)]).T
    bestfit = np.load(CIVDIST_DIR + "data/bestfit.npy")
    d = CIV_distance(data, bestfit, path=CIVDIST_DIR)
    # CIV_distance silently skips points it cannot place; check none was lost
    assert len(d) == meas.sum(), "CIV_distance dropped a point"
    t["CIV_dist"] = np.nan
    t.loc[meas, "CIV_dist"] = d
    t["spectrum"] = np.where(meas, t["adopted"], "IUE")

    lines = []
    for _, r in t.iterrows():
        if r["CIVgood_manmask"] in (2, 3):
            vals = "%d & %.1f & %.2f" % (round(r["CIV_blue"]), r["CIV_EW"], r["CIV_dist"])
        else:
            vals = r"\ldots & \ldots & \ldots"
        lines.append("  %d & %s & %s & %s & %d \\\\"
                     % (r["row_num"], r["common_name"], r["spectrum"], vals,
                        r["CIVgood_manmask"]))

    head = r"""%% Table generated by HST-Paper/paper_figures_v23/make_table2.py
%% from Data/CIV_measurements_v23.csv

\startlongtable
\begin{deluxetable}{rllrrrc}
\tablecaption{Adopted \civ\ Measurements\label{tab:civ}}
\tablewidth{0pt}
\tablehead{
  \colhead{\#\tablenotemark{a}} &
  \colhead{Common Name} &
  \colhead{Spectrum\tablenotemark{b}} &
  \colhead{Blueshift\tablenotemark{c}} &
  \colhead{EW} &
  \colhead{$D_{\rm C\,IV}$\tablenotemark{d}} &
  \colhead{Q\tablenotemark{e}} \\
  \colhead{} & \colhead{} & \colhead{} &
  \colhead{(km\,s$^{-1}$)} & \colhead{(\AA)} & \colhead{} & \colhead{}
}
\startdata
"""
    foot = r"""\enddata
\tablenotetext{a}{Index in Table~\ref{tab:master_sample}.}
\tablenotetext{b}{Spectrum the measurement was made from; SPLICE: two instruments joined, see \S2. IUE objects are not yet measured.}
\tablenotetext{c}{Positive values are blueshifted relative to systemic.}
\tablenotetext{d}{\civ\ distance: position along the best-fit curve through the SDSS quasars in the blueshift--$\log$\,EW plane [REF].}
\tablenotetext{e}{As in Table~\ref{tab:master_sample}: 3\,=\,measured; 2\,=\,measured, with a reservation; 1\,=\,IUE only, not yet measured.}
\end{deluxetable}
"""
    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, "table2_civ_v23.tex")
    open(out, "w").write(head + "\n".join(lines) + "\n" + foot)
    t[["row_num", "common_name", "spectrum", "CIV_blue", "CIV_EW", "CIV_dist",
       "CIVgood_manmask"]].to_csv(out.replace(".tex", ".csv"), index=False)
    print("wrote %s: %d rows (%d measured, %d IUE placeholders)"
          % (out, len(t), meas.sum(), (~meas).sum()))
    print(t.loc[meas, ["CIV_blue", "CIV_EW", "CIV_dist"]].describe().loc[["min", "50%", "max"]])


if __name__ == "__main__":
    main()
